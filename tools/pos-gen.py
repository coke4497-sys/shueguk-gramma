def ox(qid, stem, ans, why, hint=None):
    q = {'id': qid, 'type': 'ox', 'stem': stem, 'answer': ans, 'explanation': why}
    if hint: q['hint'] = hint
    return q


def ch(qid, stem, opts, ans, why, hint=None):
    q = {'id': qid, 'type': 'choice', 'stem': stem, 'options': opts, 'answer': ans, 'explanation': why}
    if hint: q['hint'] = hint
    return q


def sh(qid, stem, ans, why, alts=None, hint=None):
    q = {'id': qid, 'type': 'short', 'stem': stem, 'answer': ans, 'explanation': why}
    if alts: q['answers'] = alts
    if hint: q['hint'] = hint
    return q


