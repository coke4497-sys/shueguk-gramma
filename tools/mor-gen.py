def parse(spec):
    """'귀엽-:A -어:E연결 어미' → [(표기, 코드, 이름)]"""
    out = []
    for tok in re.split(r'\s+(?=\S+:[A-Z])', spec.strip()):
        form, kind = tok.split(':', 1)
        m = re.match(r'([A-Z]+)\s*(.*)$', kind)
        code, label = m.group(1), m.group(2).strip()
        name = label or KIND[code][0]
        if label and code == 'E' and not label.endswith('어미'): name = label + ' 어미'
        if label and code == 'S' and not label.endswith('접미사'): name = label + ' 접미사'
        if label and code == 'J' and not label.endswith('조사'): name = label + ' 조사'
        out.append((form, code, name))
    return out

def variants(form):
    """form은 붙임표를 포함한 대표 표기('믿-', '-음', '-었-', 조사·자립은 없음). 페이지가 그 붙임표를 빈칸 앞뒤에 표시하고
       학생은 형태소만 쓴다(2026-09-13 사용자 "조사를 제외한 의존 형태소는 - 표시가 필요합니다" → "빈칸 앞뒤로 표시")."""
    return form

def explain(ms, note=''):
    parts = [f"{f}: {n}({KIND[c][1]})" for f, c, n in ms]
    s = ' · '.join(parts) + f" — 형태소 {len(ms)}개."
    if note: s += ' ' + note
    return s

def proc(start, spec, note='', hint=''):
    ms = parse(spec)
    q = {'type': 'process', 'start': start,
         'steps': [{'accept': [KIND[c][1].split('·')[0]], 'accept2': [KIND[c][1].split('·')[1]], 'form': variants(f)} for f, c, n in ms],
         'explanation': explain(ms, note)}
    if hint: q['hint'] = hint
    return q

def short(stem, answer, answers=None, expl=''):
    q = {'type': 'short', 'stem': stem, 'answer': answer, 'explanation': expl}
    if answers: q['answers'] = answers
    return q

