def wrap(start, spec, note):
    n = note
    if n == '※': n = '※ 자료에 없는 단어를 문서 규칙으로 분석한 예.'
    elif n.startswith('※'): pass
    return proc(start, spec, n)

def count_q(start, spec, note):
    """문장 하나로 만드는 개수 단답 여러 종류"""
    ms = parse(spec)
    cls = [KIND[c][1] for f, c, n in ms]
    kinds = {
        '형태소': len(ms), '자립 형태소': cls.count('실질·자립'),
        '의존 형태소': len(ms) - cls.count('실질·자립'), '실질 형태소': cls.count('실질·자립') + cls.count('실질·의존'),
        '형식 형태소': cls.count('형식·의존'), '실질 형태소이면서 의존 형태소인 것': cls.count('실질·의존'),
    }
    lst = ' · '.join(f"{f}({KIND[c][1]})" for f, c, n in ms)
    out = []
    for k, v in kinds.items():
        stem = f"'{start}'에서 {k}는 모두 몇 개인가? (숫자만)" if k != '형태소' else f"'{start}'은/는 몇 개의 형태소로 이루어졌는가? (숫자만)"
        out.append(short(stem, str(v), [str(v), f'{v}개'], f"{lst} — {k} {v}개."))
    return out

